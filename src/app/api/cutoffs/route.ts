function buildCutoffData() {
  const data: {
    year: number;
    branchCode: string;
    branchName: string;
    generalCutoff: number;
    obCutoff: number;
    scCutoff: number;
    stCutoff: number;
    totalApplicants: number;
    totalQualified: number;
    qualifyingRate: number;
    maxMarks: number;
  }[] = [];

  for (const [code, entries] of Object.entries(BRANCH_CUTOFFS)) {
    for (const [year, general, ob, sc, st, applicants, qualified, rate, maxMarks] of entries) {
      data.push({
        year,
        branchCode: code,
        branchName: BRANCH_NAMES[code] || code,
        generalCutoff: general,
        obCutoff: ob,
        scCutoff: sc,
        stCutoff: st,
        totalApplicants: applicants,
        totalQualified: qualified,
        qualifyingRate: rate,
        maxMarks,
      });
    }
  }

  return data;
}

const CUTOFF_DATA = buildCutoffData();

export async function GET(request: Request) {
  try {
    const url = new URL(request.url);
    const branchCode = url.searchParams.get("branch");
    const year = url.searchParams.get("year");
    const category = url.searchParams.get("category") || "general";

    let data = CUTOFF_DATA;

    if (branchCode) {
      data = data.filter((c) => c.branchCode === branchCode.toUpperCase());
    }

    if (year) {
      data = data.filter((c) => c.year === parseInt(year));
    }

    // Return cutoff for the requested category
    const result = data.map((c) => {
      const cutoff =
        category === "ob"
          ? c.obCutoff
          : category === "sc"
          ? c.scCutoff
          : category === "st"
          ? c.stCutoff
          : c.generalCutoff;
      return { ...c, cutoff, category };
    });

    // Sort by year desc
    result.sort((a, b) => b.year - a.year);

    return NextResponse.json({ cutoffs: result, total: result.length });
  } catch (error) {
    console.error("[Cutoffs] Error:", error);
    return NextResponse.json({ cutoffs: [], total: 0 });
  }
}
